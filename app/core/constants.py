# Зоны по оценке модели. Общие подписи говорят о стипендии в семестре N+2 и не
# зависят от того, есть ли стипендия сейчас (нужны для сводки по группе).
RISK_BANDS = [
    # (нижняя граница, ключ, подпись)
    (0.70, "high", "Скорее всего со стипендией"),
    (0.40, "mid", "Стипендия под вопросом"),
    (0.00, "low", "Скорее всего без стипендии"),
]

# Персональная формулировка: зависит от того, есть ли у студента стипендия
# в семестре N+1 (то есть закрыт ли семестр N без троек, долгов и пересдач).
VERDICT_LABELS = {
    ("high", True): "Скорее всего сохранит стипендию",
    ("mid", True): "Стипендия под вопросом",
    ("low", True): "Скорее всего потеряет стипендию",
    ("high", False): "Скорее всего получит стипендию",
    ("mid", False): "Стипендия под вопросом",
    ("low", False): "Скорее всего останется без стипендии",
}


def risk_band(prob: float) -> tuple[str, str]:
    """Вернуть (ключ, общая подпись) зоны для оценки вероятности."""
    for lower, key, label in RISK_BANDS:
        if prob >= lower:
            return key, label
    return RISK_BANDS[-1][1], RISK_BANDS[-1][2]


def verdict_label(key: str, has_stipend_now: bool) -> str:
    """Персональная подпись зоны: сохранит / потеряет для тех, у кого стипендия
    есть, получит / останется без - для тех, у кого ее нет."""
    return VERDICT_LABELS[(key, bool(has_stipend_now))]
